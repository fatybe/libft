#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*str;

	i = 0;
	if (n == 0)
		return (s);
	str = (unsigned char *)s;
	while (i < n)
	{
		str[i] = (unsigned char)c;
		i++;
	}
	return (s);
}
#include<stdio.h>
int	main(void)
{
	int vv[10] = {0};
	ft_memset(vv,5, 1);
	printf("%s\n",vv);
}
